// ——— Портфель v2: несколько счетов в одном JSON (синхронизируется с /api/portfolio) ———
var _portfolioBundleCache = null;

function invalidatePortfolioBundleCache() {
  _portfolioBundleCache = null;
}

function normalizeHoldings(h) {
  if (!h || typeof h !== 'object') return { stocks: [], crypto: [], futuresValueRub: 0 };
  return {
    stocks: Array.isArray(h.stocks) ? h.stocks.filter(x => x && typeof x.ticker === 'string' && Number.isFinite(x.quantity) && x.quantity > 0) : [],
    crypto: Array.isArray(h.crypto) ? h.crypto.filter(x => x && typeof x.symbol === 'string' && Number.isFinite(x.amount) && x.amount > 0) : [],
    futuresValueRub: Number.isFinite(h.futuresValueRub) && h.futuresValueRub >= 0 ? h.futuresValueRub : 0
  };
}

function normalizeBundleAccounts(b) {
  if (!b.accounts || !Array.isArray(b.accounts)) b.accounts = [];
  b.accounts = b.accounts.filter(a => a && typeof a === 'object');
  if (!b.accounts.length) b.accounts.push({ id: 'acc_main', name: 'Основной счёт', balanceRub: 0, holdings: {} });
  b.accounts.forEach(function (a) {
    if (!a.id) a.id = 'acc_' + Math.random().toString(36).slice(2, 10);
    if (!a.name) a.name = 'Счёт';
    a.balanceRub = Number(a.balanceRub);
    if (!Number.isFinite(a.balanceRub) || a.balanceRub < 0) a.balanceRub = 0;
    a.holdings = normalizeHoldings(a.holdings);
  });
  if (!b.activeId || !b.accounts.some(function (x) { return x.id === b.activeId; })) {
    b.activeId = b.accounts[0] ? b.accounts[0].id : 'acc_main';
  }
}

function getActiveAccountRef(b) {
  if (!b || !b.accounts || !b.accounts.length) return null;
  var a = b.accounts.find(function (x) { return x.id === b.activeId; });
  return a || b.accounts[0];
}

function persistPortfolioBundle(b) {
  normalizeBundleAccounts(b);
  _portfolioBundleCache = b;
  try {
    var json = JSON.stringify(b);
    if (!isLocalOnlyScopedStorage() && typeof db !== 'undefined' && db.setPortfolioJson) db.setPortfolioJson(json);
    lsSetScoped('rubliks_portfolio', json);
    var acc = getActiveAccountRef(b);
    if (acc) {
      lsSetScoped('rubliks_balance', String(acc.balanceRub));
      if (!isLocalOnlyScopedStorage() && typeof db !== 'undefined' && db.setBalance) db.setBalance(acc.balanceRub);
    }
  } catch (e) { }
}

function loadBundleFromStorage() {
  if (_portfolioBundleCache) return _portfolioBundleCache;
  var raw = null;
  try {
    if (!isLocalOnlyScopedStorage()) {
      raw = typeof db !== 'undefined' && db.getPortfolioJson ? db.getPortfolioJson() : null;
    }
    if (!raw) raw = lsGetScoped('rubliks_portfolio');
  } catch (e0) {}
  var parsed = null;
  try {
    parsed = raw ? JSON.parse(raw) : null;
  } catch (e1) {
    parsed = null;
  }
  var balLegacy = 133081.30;
  try {
    var bv = null;
    if (!isLocalOnlyScopedStorage()) bv = typeof db !== 'undefined' && db.getBalance ? db.getBalance() : null;
    if (bv == null) bv = lsGetScoped('rubliks_balance');
    if (bv != null) {
      var n = parseFloat(bv);
      if (!isNaN(n)) balLegacy = n;
    }
  } catch (e2) {}

  if (parsed && parsed.v === 2 && Array.isArray(parsed.accounts) && parsed.accounts.length) {
    normalizeBundleAccounts(parsed);
    _portfolioBundleCache = parsed;
    return _portfolioBundleCache;
  }
  var leg = parsed && typeof parsed === 'object' ? parsed : { stocks: [], crypto: [], futuresValueRub: 0 };
  if (!Array.isArray(leg.stocks)) leg.stocks = [];
  if (!Array.isArray(leg.crypto)) leg.crypto = [];
  if (leg.futuresValueRub == null) leg.futuresValueRub = 0;
  _portfolioBundleCache = {
    v: 2,
    activeId: 'acc_main',
    accounts: [{
      id: 'acc_main',
      name: 'Основной счёт',
      balanceRub: balLegacy,
      holdings: {
        stocks: leg.stocks.slice(),
        crypto: leg.crypto.slice(),
        futuresValueRub: leg.futuresValueRub
      }
    }]
  };
  persistPortfolioBundle(_portfolioBundleCache);
  return _portfolioBundleCache;
}

