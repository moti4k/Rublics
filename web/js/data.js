function getAccounts() {
  if (typeof authApi !== 'undefined' && authApi.isUsingBackend()) return [];
  try {
    if (typeof db !== 'undefined' && db.getAccounts) {
      var list = db.getAccounts();
      if (list && list.length > 0) return list;
    }
    if (typeof localStorage !== 'undefined') {
      var v = localStorage.getItem('rubliks_accounts');
      if (v) return JSON.parse(v);
    }
  } catch (e) { }
  return [];
}

function saveAccounts(accounts) {
  if (typeof authApi !== 'undefined' && authApi.isUsingBackend()) return;
  try {
    if (typeof db !== 'undefined' && db.saveAccounts) db.saveAccounts(accounts);
    if (typeof localStorage !== 'undefined') localStorage.setItem('rubliks_accounts', JSON.stringify(accounts));
  } catch (e) { }
}

function findAccount(email, password) {
  var norm = String(email).trim().toLowerCase();
  return getAccounts().find(function (a) {
    return a.email.toLowerCase() === norm && a.password === password;
  });
}

function registerUser(email, password, displayName) {
  if (typeof authApi !== 'undefined' && authApi.isUsingBackend()) {
    return authApi.register(email, password, displayName || '').then(function () { return true; }).catch(function (e) { throw e; });
  }
  var norm = String(email).trim().toLowerCase();
  if (!norm || !password) return false;
  var accounts = getAccounts();
  if (accounts.some(function (a) { return a.email.toLowerCase() === norm; })) return false;
  var account = {
    email: norm,
    password: password,
    displayName: (displayName || '').trim() || norm,
    createdAt: new Date().toISOString()
  };
  accounts.push(account);
  saveAccounts(accounts);
  setCurrentUser({ email: account.email, displayName: account.displayName, createdAt: account.createdAt });
  return true;
}

function loginUser(email, password) {
  if (typeof authApi !== 'undefined' && authApi.isUsingBackend()) {
    return authApi.login(email, password).then(function () { return true; }).catch(function (e) { throw e; });
  }
  var account = findAccount(email, password);
  if (!account) return false;
  setCurrentUser({ email: account.email, displayName: account.displayName, createdAt: account.createdAt });
  return true;
}

function getCurrentUser() {
  if (typeof authApi !== 'undefined' && authApi.isUsingBackend()) {
    return authApi.getCurrentUserSync() || null;
  }
  try {
    if (!isLocalOnlyScopedStorage() && typeof db !== 'undefined' && db.getCurrentUser) {
      var u = db.getCurrentUser();
      if (u) return u;
    }
    if (typeof localStorage !== 'undefined') {
      var v = localStorage.getItem('rubliks_current_user');
      if (v) return JSON.parse(v);
    }
  } catch (e) { }
  return null;
}

function setCurrentUser(profile) {
  if (typeof authApi !== 'undefined' && authApi.isUsingBackend()) { return; }
  try {
    var prevEmail = null;
    try {
      if (typeof localStorage !== 'undefined') {
        var raw = localStorage.getItem('rubliks_current_user');
        if (raw) {
          var pu = JSON.parse(raw);
          if (pu && pu.email) prevEmail = String(pu.email).toLowerCase();
        }
      }
    } catch (e0) {}
    if (!isLocalOnlyScopedStorage() && typeof db !== 'undefined' && db.setCurrentUser) db.setCurrentUser(profile);
    if (typeof localStorage !== 'undefined') localStorage.setItem('rubliks_current_user', profile ? JSON.stringify(profile) : '');
    if (isLocalOnlyScopedStorage()) {
      var ne = profile && profile.email ? String(profile.email).toLowerCase() : null;
      if (prevEmail !== ne) invalidatePortfolioBundleCache();
    }
  } catch (e) { }
}

/** Режим «только гость»: без экрана входа, один локальный профиль (данные с суффиксом по email гостя). */
function ensureLocalGuestUser() {
  try {
    if (typeof RUBLIKS_GUEST_ONLY === 'undefined' || !RUBLIKS_GUEST_ONLY) return;
    if (typeof RUBLIKS_LOCAL_ONLY === 'undefined' || !RUBLIKS_LOCAL_ONLY) return;
    if (getCurrentUser()) return;
    setCurrentUser({
      email: 'guest@local.rubliks',
      displayName: 'Гость',
      createdAt: new Date().toISOString(),
      localOnly: true,
      guest: true
    });
  } catch (e) {}
}

function isGuestOnlyMode() {
  return typeof RUBLIKS_GUEST_ONLY !== 'undefined' && RUBLIKS_GUEST_ONLY &&
    typeof RUBLIKS_LOCAL_ONLY !== 'undefined' && RUBLIKS_LOCAL_ONLY;
}

// ——— User-scoped localStorage (не трогаем rubliks_accounts, rubliks_current_user, токены API) ———
function getStorageUserSuffix() {
  try {
    if (typeof authApi !== 'undefined' && authApi.getCurrentUserSync) {
      var u = authApi.getCurrentUserSync();
      if (u && u.id != null) return 'id' + String(u.id);
    }
  } catch (e0) {}
  try {
    var cu = getCurrentUser();
    if (cu && cu.email) return 'em_' + String(cu.email).toLowerCase().replace(/[^a-z0-9@._-]/g, '_');
  } catch (e1) {}
  return 'anon';
}

function lsGetScoped(baseKey) {
  try {
    if (typeof localStorage === 'undefined') return null;
    var scoped = baseKey + '__' + getStorageUserSuffix();
    var v = localStorage.getItem(scoped);
    if (v != null) return v;
    return null;
  } catch (e) { return null; }
}

function lsSetScoped(baseKey, value) {
  try {
    if (typeof localStorage === 'undefined') return;
    var scoped = baseKey + '__' + getStorageUserSuffix();
    localStorage.setItem(scoped, value);
  } catch (e) {}
}

function logoutUser() {
  invalidatePortfolioBundleCache();
  if (typeof authApi !== 'undefined' && authApi.isUsingBackend()) {
    authApi.logout();
    setFriendsCache(null);
    return;
  }
  try {
    setFriendsCache(null);
    if (!isLocalOnlyScopedStorage() && typeof db !== 'undefined' && db.setCurrentUser) db.setCurrentUser(null);
    if (typeof localStorage !== 'undefined') localStorage.removeItem('rubliks_current_user');
  } catch (e) { }
}

