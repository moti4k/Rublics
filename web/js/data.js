function shuffleArrayInPlace(arr) {
  var i;
  for (i = arr.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var t = arr[i];
    arr[i] = arr[j];
    arr[j] = t;
  }
  return arr;
}

/** Квиз: вопросы по уровню из входного теста + один «челлендж» уровнем выше (как в теории к дневному тесту). */
function getQuizDeck() {
  var deckSize = 8;
  var bank = DATA.quizItems || [];
  if (!bank.length) return [];
  function lev(q) {
    return q.level != null ? q.level : 2;
  }
  var lvl = getInvestorLevel();
  var maxL = lvl === 'pro' ? 3 : (lvl === 'explorer' ? 2 : 1);
  var pool = bank.filter(function (q) {
    return lev(q) <= maxL;
  });
  if (pool.length < 5) {
    pool = bank.filter(function (q) {
      return lev(q) <= maxL + 1;
    });
  }
  shuffleArrayInPlace(pool);
  var deck = pool.slice(0, Math.min(deckSize, pool.length));
  var challengePool = bank.filter(function (q) {
    return lev(q) === maxL + 1 && maxL < 3;
  });
  if (challengePool.length && deck.length >= 4 && maxL < 3 && Math.random() < 0.55) {
    shuffleArrayInPlace(challengePool);
    deck[deck.length - 1] = challengePool[0];
  }
  var fillCap = maxL < 3 ? maxL + 1 : 3;
  if (deck.length < deckSize) {
    var rest = bank.filter(function (q) {
      return deck.indexOf(q) < 0 && lev(q) <= fillCap;
    });
    shuffleArrayInPlace(rest);
    var k;
    for (k = 0; k < rest.length && deck.length < deckSize; k++) deck.push(rest[k]);
  }
  return deck;
}

function pickVictorinaDeck(count) {
  count = count || 10;
  var lvl = getInvestorLevel();
  var maxL = lvl === 'pro' ? 3 : (lvl === 'explorer' ? 2 : 1);
  var pool = (DATA.victorinaQuestions || []).filter(function (q) { return q.level <= maxL + 1; });
  if (pool.length < count) pool = (DATA.victorinaQuestions || []).slice();
  var arr = pool.slice();
  shuffleArrayInPlace(arr);
  return arr.slice(0, count);
}
